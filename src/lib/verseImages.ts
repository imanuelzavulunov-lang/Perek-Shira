export function getVerseImage(id: string): string {
  return VERSE_IMAGES[id] || 'https://images.unsplash.com/photo-1470071459604-3b5ec3a7fe05?auto=format&fit=crop&w=600&q=80';
}

/**
 * Returns full quality uncompressed/original URL of the image
 */
export function getFullQualityImageUrl(url: string): string {
  if (!url) return '';
  if (url.includes('unsplash.com')) {
    const base = url.split('?')[0];
    return `${base}?auto=format&fit=crop&w=2400&q=100`;
  }
  if (url.includes('i.ibb.co')) {
    const base = url.split('?')[0];
    return `${base}?auto=format&q=100`;
  }
  return url;
}

export interface ImageDownloadItem {
  id: string;
  chapterId: number;
  chapterHebrew: string;
  verseNumber: number;
  title: string;
  url: string;
  fullQualityUrl: string;
  folderName: string;
  fileName: string;
}

/**
 * Strips Hebrew vowels (nikkud) for clean file and folder names
 */
export function stripNikkud(text: string): string {
  return text.replace(/[\u0591-\u05C7]/g, '').trim();
}

/**
 * Returns all images in Perek Shira with clean paths and full quality URLs
 */
export function getAllPerekShiraImages(): ImageDownloadItem[] {
  const items: ImageDownloadItem[] = [];

  const chapterNamesHebrew: Record<number, string> = {
    1: 'פרק א - שמים וארץ',
    2: 'פרק ב - יום ולילה ומאורות',
    3: 'פרק ג - אילנות וצמחים',
    4: 'פרק ד - עופות ודגים',
    5: 'פרק ה - בהמות וחיות',
    6: 'פרק ו - שרצים וכלבים',
  };

  PEREK_SHIRA_DATA.forEach((chapter) => {
    chapter.verses.forEach((verse, idx) => {
      const imgUrl = VERSE_IMAGES[verse.id];
      if (!imgUrl) return;

      const cleanTitle = stripNikkud(verse.titleHebrew)
        .replace(/[\\/:*?"<>|]/g, '_')
        .replace(/\s+/g, '_');
      
      const cleanChapterFolder = `${chapter.id}_${stripNikkud(chapterNamesHebrew[chapter.id] || chapter.titleHebrew).replace(/[\\/:*?"<>|]/g, '_')}`;
      
      // Determine file extension
      let ext = 'jpg';
      const cleanUrl = imgUrl.split('?')[0].toLowerCase();
      if (cleanUrl.endsWith('.png')) ext = 'png';
      else if (cleanUrl.endsWith('.avif')) ext = 'avif';
      else if (cleanUrl.endsWith('.webp')) ext = 'webp';
      else if (cleanUrl.endsWith('.jpeg') || cleanUrl.endsWith('.jpg')) ext = 'jpg';

      const padNum = String(idx + 1).padStart(2, '0');
      const fileName = `${padNum}_${cleanTitle}.${ext}`;

      items.push({
        id: verse.id,
        chapterId: chapter.id,
        chapterHebrew: chapter.titleHebrew,
        verseNumber: idx + 1,
        title: stripNikkud(verse.titleHebrew),
        url: imgUrl,
        fullQualityUrl: getFullQualityImageUrl(imgUrl),
        folderName: cleanChapterFolder,
        fileName,
      });
    });
  });

  return items;
}
